-- Additive session storage for stateless containers; domain records are unchanged.
CREATE TABLE credlearn_http_sessions (
 PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY,
 SESSION_ID CHAR(36) NOT NULL,
 CREATION_TIME BIGINT NOT NULL,
 LAST_ACCESS_TIME BIGINT NOT NULL,
 MAX_INACTIVE_INTERVAL INT NOT NULL,
 EXPIRY_TIME BIGINT NOT NULL,
 PRINCIPAL_NAME VARCHAR(100),
 UNIQUE KEY idx_http_session_id (SESSION_ID),
 INDEX idx_http_session_expiry (EXPIRY_TIME),
 INDEX idx_http_session_principal (PRINCIPAL_NAME)
) ENGINE=InnoDB ROW_FORMAT=DYNAMIC;
CREATE TABLE credlearn_http_sessions_ATTRIBUTES (
 SESSION_PRIMARY_ID CHAR(36) NOT NULL,
 ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
 ATTRIBUTE_BYTES BLOB NOT NULL,
 PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
 CONSTRAINT fk_http_session_attribute FOREIGN KEY (SESSION_PRIMARY_ID)
  REFERENCES credlearn_http_sessions(PRIMARY_ID) ON DELETE CASCADE
) ENGINE=InnoDB ROW_FORMAT=DYNAMIC;
